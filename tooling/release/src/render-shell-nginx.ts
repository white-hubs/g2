import { mkdirSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";

export function shellPrefixFromPcShellKey(pcShellKey: string): string {
  const slash = pcShellKey.lastIndexOf("/");
  if (slash <= 0) {
    throw new Error(`invalid pcShell key (expected logicalName/version/file): ${pcShellKey}`);
  }
  return pcShellKey.slice(0, slash);
}

export function renderShellNginxConf(prefix: string): string {
  // Named locations cannot use proxy_pass with a URI path — rewrite then proxy_pass host-only.
  // MinIO returns ListBucketResult/NoSuchKey for bare prefix "/"; map "/" → index.html explicitly.
  // Host must be the MinIO service (path-style), not the browser Host.
  return `# generated by @g2-tooling/release — do not edit
location = / {
  proxy_pass http://minio:9000/g2-web-release/${prefix}/index.html;
  proxy_set_header Host minio:9000;
}
location / {
  error_page 404 = @shell_fallback;
  proxy_intercept_errors on;
  proxy_pass http://minio:9000/g2-web-release/${prefix}/;
  proxy_set_header Host minio:9000;
}
location @shell_fallback {
  rewrite ^ /g2-web-release/${prefix}/index.html break;
  proxy_pass http://minio:9000;
  proxy_set_header Host minio:9000;
}
`;
}

export function renderShellNginxFromPcShellKey(pcShellKey: string): string {
  return renderShellNginxConf(shellPrefixFromPcShellKey(pcShellKey));
}

export function writeShellNginxConf(outPath: string, pcShellKey: string, options?: { dryRun?: boolean }): string {
  const content = renderShellNginxFromPcShellKey(pcShellKey);

  if (options?.dryRun) {
    console.log(`[release] shell nginx (dry-run): would write ${outPath}`);
    console.log(content);
    return outPath;
  }

  mkdirSync(dirname(outPath), { recursive: true });
  writeFileSync(outPath, content, "utf8");
  console.log(`[release] wrote ${outPath}`);
  return outPath;
}
