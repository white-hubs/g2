import { describe, expect, test } from "bun:test";

import { renderShellNginxConf, renderShellNginxFromPcShellKey, shellPrefixFromPcShellKey } from "./render-shell-nginx";

describe("renderShellNginx", () => {
  test("derives shell prefix from pcShell key", () => {
    expect(shellPrefixFromPcShellKey("pcShell/20260722.abc/index.html")).toBe("pcShell/20260722.abc");
  });

  test("renders SPA-aware proxy with prefix", () => {
    const conf = renderShellNginxFromPcShellKey("pcShell/20260722.abc/index.html");
    expect(conf).toContain("location = / {\n  proxy_pass http://minio:9000/g2-web-release/pcShell/20260722.abc/index.html;");
    expect(conf).toContain("proxy_pass http://minio:9000/g2-web-release/pcShell/20260722.abc/;");
    expect(conf).toContain("rewrite ^ /g2-web-release/pcShell/20260722.abc/index.html break;");
    expect(conf).toContain("proxy_set_header Host minio:9000;");
    expect(conf).toContain(
      "location @shell_fallback {\n  rewrite ^ /g2-web-release/pcShell/20260722.abc/index.html break;\n  proxy_pass http://minio:9000;",
    );
    expect(conf).toContain("error_page 404 = @shell_fallback;");
    expect(conf).toContain("# generated by @g2-tooling/release");
  });

  test("renderShellNginxConf uses provided prefix", () => {
    const conf = renderShellNginxConf("pcShell/00000000.local");
    expect(conf).toContain("g2-web-release/pcShell/00000000.local/");
  });
});
